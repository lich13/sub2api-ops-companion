-- Isolated PostgreSQL schema for usage-record parity tests.
-- Deliberately omits foreign keys so historical rows can outlive directory rows.
CREATE TABLE users (
    id bigint PRIMARY KEY,
    username text,
    email text,
    status text,
    deleted_at timestamptz,
    password text,
    credentials text
);

CREATE TABLE api_keys (
    id bigint PRIMARY KEY,
    name text,
    user_id bigint,
    status text,
    deleted_at timestamptz,
    key text,
    token text
);

CREATE TABLE accounts (
    id bigint PRIMARY KEY,
    name text,
    platform text,
    type text,
    status text,
    schedulable boolean,
    credentials jsonb,
    extra jsonb,
    parent_account_id bigint,
    priority integer,
    concurrency integer,
    load_factor integer,
    proxy_id bigint,
    temp_unschedulable_until timestamptz,
    temp_unschedulable_reason text,
    rate_limited_at timestamptz,
    rate_limit_reset_at timestamptz,
    overload_until timestamptz,
    error_message text,
    error_code text,
    error_status_code integer,
    expires_at timestamptz,
    auto_pause_on_expired boolean,
    created_at timestamptz,
    updated_at timestamptz,
    deleted_at timestamptz
);

CREATE TABLE groups (
    id bigint PRIMARY KEY,
    name text,
    platform text,
    sort_order integer,
    model_allowlist jsonb,
    codex_models_manifest_config jsonb,
    max_reasoning_effort text,
    max_reasoning_effort_over_limit text,
    reasoning_effort_mappings jsonb,
    updated_at timestamptz,
    deleted_at timestamptz
);

CREATE TABLE account_groups (
    account_id bigint,
    group_id bigint,
    PRIMARY KEY (account_id, group_id)
);

CREATE TABLE usage_logs (
    id bigint PRIMARY KEY,
    user_id bigint,
    api_key_id bigint,
    account_id bigint,
    group_id bigint,
    upstream_model_mismatch boolean,
    request_type integer,
    stream boolean,
    openai_ws_mode boolean,
    input_tokens bigint,
    output_tokens bigint,
    cache_creation_tokens bigint,
    cache_read_tokens bigint,
    cache_creation_5m_tokens bigint,
    cache_creation_1h_tokens bigint,
    first_token_ms bigint,
    duration_ms bigint,
    image_count bigint,
    image_output_tokens bigint,
    image_input_tokens bigint,
    video_count bigint,
    input_cost numeric,
    output_cost numeric,
    cache_creation_cost numeric,
    cache_read_cost numeric,
    total_cost numeric,
    actual_cost numeric,
    account_stats_cost numeric,
    account_rate_multiplier numeric,
    rate_multiplier numeric,
    image_output_cost numeric,
    image_input_cost numeric,
    video_duration_seconds numeric,
    created_at timestamptz,
    request_id text,
    upstream_request_id text,
    model text,
    requested_model text,
    upstream_model text,
    upstream_response_model text,
    model_mapping_chain text,
    reasoning_effort text,
    requested_reasoning_effort text,
    user_agent text,
    ip_address text,
    inbound_endpoint text,
    upstream_endpoint text,
    billing_type text,
    billing_mode text,
    service_tier text,
    video_resolution text,
    credentials text,
    request_headers text,
    response_headers text,
    request_body text,
    response_body text
);

CREATE TABLE ops_error_logs (
    id bigint PRIMARY KEY,
    account_id bigint,
    group_id bigint,
    created_at timestamptz,
    platform text,
    error_owner text,
    error_phase text,
    error_source text,
    stream boolean,
    model text,
    requested_model text,
    upstream_model text,
    status_code integer,
    upstream_status_code integer,
    provider_error_code text,
    provider_error_type text,
    network_error_type text,
    error_type text,
    error_message text,
    upstream_error_message text,
    error_body text,
    upstream_error_detail text,
    upstream_errors jsonb,
    request_id text,
    client_request_id text,
    resolved boolean
);
